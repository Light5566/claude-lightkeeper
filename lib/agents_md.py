#!/usr/bin/env python3
"""vault export --agents-md: print a short block for AGENTS.md (or CLAUDE.md,
GEMINI.md, ...) so agents without Lightkeeper's hooks still find the map:
where it is, how to search it, and which note owns which code.

It only prints. Nothing is written: paste the block yourself, or let your
agent put it in so you see the diff. To refresh, run it again and replace
what sits between the two markers. Never called from a hook.
Python 3.9, stdlib only.
"""
import os
import re
import sys
from pathlib import Path

import vaultlib

BEGIN = "<!-- lightkeeper:begin (generated by `vault export --agents-md`; run it again to refresh) -->"
END = "<!-- lightkeeper:end -->"
MAX_ROWS = 15
MAX_FILES = 3


def home(path):
    p, h = str(path), str(Path.home())
    return "~" + p[len(h):] if p == h or p.startswith(h + os.sep) else p


def scrub(url):
    """The remote without any user:password@ part: the block may get committed."""
    return re.sub(r"^([a-z+]+://)[^/@]+@", r"\1", url.strip()) if url else None


def cell(text):
    return vaultlib.trim(text or "", 100).replace("|", "\\|")


def render(idx, name, root, repo=None, remote=None):
    owned = {}
    for path, stems in idx["paths"].items():
        for s in stems:
            owned.setdefault(s, []).append(path)
    rows = [(s, n) for s, n in idx["notes"].items()
            if n.get("type") in ("module", "integration") and owned.get(s)
            and (not repo or n.get("repo") in ("", "both", repo))]
    rows.sort(key=lambda r: (r[1].get("depth") == "stub", -r[1].get("inbound", 0), r[0].lower()))
    where = "`%s`" % home(root) + (", cloned from `%s`" % remote if remote else "")
    lines = [
        BEGIN, "## Codebase map", "",
        "This repository has a knowledge map kept outside the code: markdown notes on how each "
        "module works, what else a change there touches, and the traps to know first. It is the "
        "%s vault (%s)." % (name, where), "",
        "- Before changing an area, read its note: **How it works** and **Gotchas** first; "
        "**Connects to** says what else a change there touches, and why.",
        "- Find notes with `vault find <words>` or `vault find --paths <files>` when the "
        "Lightkeeper CLI is installed; otherwise search the vault's markdown.",
        "- After a change that alters behaviour, update the owning note in the same piece of "
        "work: amend How it works or Gotchas, and bump `updated:`.",
    ]
    if remote:
        lines.append("- No copy of the vault yet? Run `vault init --clone %s --repo .` "
                     "in this checkout." % remote)
    if rows:
        lines += ["", "| Note | What it covers | Code |", "|---|---|---|"]
        for s, n in rows[:MAX_ROWS]:
            files = owned[s]
            code = ", ".join("`%s`" % f for f in files[:MAX_FILES])
            if len(files) > MAX_FILES:
                code += " +%d more" % (len(files) - MAX_FILES)
            stub = " (stub)" if n.get("depth") == "stub" else ""
            lines.append("| `%s`%s | %s | %s |" % (n["path"], stub, cell(n.get("summary")), code))
        if len(rows) > MAX_ROWS:
            lines += ["", "%d more notes own code here; search the vault for them."
                      % (len(rows) - MAX_ROWS)]
    lines.append(END)
    return "\n".join(lines)


def main(vault=None, repo=None):
    root = vaultlib.require(root=vault)
    repos = vaultlib.CONFIG.get("repos") or {}
    if repo and repos and repo not in repos:
        sys.exit("vault: no repo %r in this vault; it covers %s" % (repo, ", ".join(sorted(repos))))
    if not repo:
        if vaultlib.MATCHED_REPO:
            repo = vaultlib.MATCHED_REPO[0]
        elif len(repos) == 1:
            repo = next(iter(repos))
        elif repos:
            sys.exit("vault: this vault covers %s; run this from one of those checkouts, "
                     "or pass --repo KEY" % ", ".join(sorted(repos)))
    remote = scrub(vaultlib._git(["remote", "get-url", "origin"], str(root)))
    name = vaultlib.CONFIG.get("name") or root.name
    print(render(vaultlib.load_index(root), name, root, repo, remote))
